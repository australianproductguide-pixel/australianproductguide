function mergeEvidenceSources(existing,additions){
  const out=[...(existing||[])];
  const seen=new Set(out.map(item=>String(typeof item==='string'?item:item&&item.url||'')));
  for(const item of additions||[]){if(!seen.has(item.url)){out.push(item);seen.add(item.url);}}
  return out;
}
